// Regenerates the `flow` dropdown in .github/workflows/remote-test-runner.yml
// from the committed flow catalog.
//
// Why this exists: the Test Runner page needs the app to be running somewhere,
// so it is unavailable whenever the machine serving it is off. The Actions UI is
// always up and already authenticates against GitHub, which makes it the runner
// surface that works when nobody's laptop is on. For that to be usable it needs
// a real picker rather than a free-text box, and the picker has to track the
// specs on its own.
//
// CI runs this next to discover-flows.js and commits both files together, so the
// dropdown never drifts from the catalog.
//
// Usage:
//   node scripts/test-runner/sync-workflow-inputs.js
//   node scripts/test-runner/sync-workflow-inputs.js --check

const fs = require("node:fs");
const path = require("node:path");

const { REPO_ROOT, requireCatalog } = require("./catalog.js");

const WORKFLOW_PATH = path.join(
  REPO_ROOT,
  ".github",
  "workflows",
  "remote-test-runner.yml",
);

const BEGIN = "      # BEGIN generated flow options";
const END = "      # END generated flow options";

// The describe-level tier is deliberately left out of the dropdown: it roughly
// doubles the list for the least-used entries, and workflow_dispatch choice
// lists have no documented size limit worth betting on. Those flows stay
// reachable through flow_override, the page, and the CLI.
const DROPDOWN_KINDS = new Set(["group", "spec"]);

function printHelp() {
  console.log(`Usage:
  node scripts/test-runner/sync-workflow-inputs.js [--check]

Rewrites the generated flow dropdown in
.github/workflows/remote-test-runner.yml from the committed flow catalog.

  --check    Exit 1 if the workflow dropdown is out of date.
  --help     Show this help.`);
}

// The generated block has to match the line endings already in the file. Writing
// LF into a CRLF working copy produces a mixed-ending file, which fails
// format:check even though the content is correct.
function detectEol(source) {
  return source.includes("\r\n") ? "\r\n" : "\n";
}

function buildBlock(catalog, eol) {
  const flows = catalog.flows.filter((flow) => DROPDOWN_KINDS.has(flow.kind));

  const lines = [
    BEGIN,
    "      # Regenerated by scripts/test-runner/sync-workflow-inputs.js.",
    "      # Do not hand-edit: CI rewrites this block when specs change.",
    "      flow:",
    '        description: "Flow to run"',
    "        required: true",
    "        default: group-sanity",
    "        type: choice",
    "        options:",
  ];

  for (const flow of flows) {
    lines.push(`          - ${flow.id}`);
  }

  lines.push(END);

  return lines.join(eol);
}

function rewrite(source, block) {
  const beginIndex = source.indexOf(BEGIN);
  const endIndex = source.indexOf(END);

  if (beginIndex === -1 || endIndex === -1) {
    throw new Error(
      `Could not find the generated markers in ${path.relative(REPO_ROOT, WORKFLOW_PATH)}. Expected lines "${BEGIN.trim()}" and "${END.trim()}".`,
    );
  }

  if (endIndex < beginIndex) {
    throw new Error("Generated markers are out of order in the workflow file.");
  }

  return (
    source.slice(0, beginIndex) + block + source.slice(endIndex + END.length)
  );
}

function main() {
  const args = process.argv.slice(2);

  if (args.includes("--help") || args.includes("-h")) {
    printHelp();
    return;
  }

  const check = args.includes("--check");
  const unknown = args.filter(
    (arg) => !["--check", "--help", "-h"].includes(arg),
  );

  if (unknown.length > 0) {
    console.error(`Unknown argument: ${unknown[0]}`);
    printHelp();
    process.exit(1);
  }

  const catalog = requireCatalog();
  const current = fs.readFileSync(WORKFLOW_PATH, "utf8");
  const next = rewrite(current, buildBlock(catalog, detectEol(current)));
  const count = catalog.flows.filter((flow) =>
    DROPDOWN_KINDS.has(flow.kind),
  ).length;

  if (current === next) {
    console.log(`[runner] Workflow dropdown is current: ${count} flows.`);
    return;
  }

  if (check) {
    console.error(
      "[runner] Workflow flow dropdown is stale. Regenerate it with: npm run flows:sync-workflow",
    );
    process.exit(1);
  }

  fs.writeFileSync(WORKFLOW_PATH, next);
  console.log(
    `[runner] Updated the workflow flow dropdown: ${count} flows (groups + spec files).`,
  );
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(`[runner] ${error.message}`);
    process.exit(1);
  }
}

module.exports = { buildBlock, detectEol, rewrite, WORKFLOW_PATH };
